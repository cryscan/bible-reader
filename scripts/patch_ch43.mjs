// 1. patch isaiah_meta_4.js：替换43章条目
const meta4Path = 'src/data/isaiah_meta_4.js'
let meta4 = fs.readFileSync(meta4Path, 'utf-8')

const secStr = ch43.sec.map(s => `{r:'${s.r}',h:'${s.h}',c:'${s.c}'}`).join(',')
const newLine = `{n:43,t:'${ch43.t}',b:'${ch43.b}',su:'${ch43.su}',sec:[${secStr}],},\n`

meta4 = meta4.replace(/\{n:43,[^\n]*\},\n/, newLine)
